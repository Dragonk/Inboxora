const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', '..');
const nativeCopy = require('../native-shell/native-copy.json');
const aliases = {
  compose: 'sidebar.compose', calendar: 'calendar.title', contacts: 'contacts.title', sync: 'messageList.sync',
  reply: 'message.reply', delete: 'common.delete', star: 'message.star', cancel: 'common.cancel',
  copy: 'common.copy', undo: 'common.undo', selectAll: 'messageList.selectAll', reload: 'queue.refresh',
  close: 'common.close', noSubject: 'common.noSubject', preferences: 'accountUi.accountSettings', services: 'accountUi.services',
};
const languageDirectories = { en: 'values', pl: 'values-pl', de: 'values-de', cs: 'values-cs', fr: 'values-fr', es: 'values-es', it: 'values-it', ru: 'values-ru', zhCN: 'values-zh-rCN' };
const androidName = key => `native_${key.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`)}`;
function buildOutputs() {
  const catalog = {};
  const expected = Object.keys(nativeCopy.en).sort();
  for (const language of Object.keys(languageDirectories)) {
    const copy = nativeCopy[language];
    if (!copy || JSON.stringify(Object.keys(copy).sort()) !== JSON.stringify(expected)) throw new Error(`Incomplete native locale: ${language}`);
    const ui = JSON.parse(fs.readFileSync(path.join(root, 'src', 'locales', `${language}.json`), 'utf8'));
    catalog[language] = { ...copy };
    for (const [key, source] of Object.entries(aliases)) {
      const value = source.split('.').reduce((object, part) => object?.[part], ui);
      if (typeof value !== 'string' || !value.trim()) throw new Error(`Missing native label: ${language}:${source}`);
      catalog[language][key] = value;
    }
    for (const [key, value] of Object.entries(catalog[language])) {
      if (typeof value !== 'string' || !value.trim()) throw new Error(`Empty native label: ${language}:${key}`);
      const tokens = text => (text.match(/\{\{\w+\}\}/g) || []).sort().join(',');
      if (nativeCopy.en[key] && tokens(value) !== tokens(nativeCopy.en[key])) throw new Error(`Invalid interpolation: ${language}:${key}`);
    }
  }
  const outputs = new Map();
  const encoded = JSON.stringify(catalog, null, 2) + '\n';
  outputs.set('packages/native-shell/locale-data.json', encoded);
  outputs.set('packages/native-shell/locales.js', `// Generated by packages/scripts/generate-native-locales.cjs. Do not edit.\n(function (root) {\n  const catalog = ${JSON.stringify(catalog)};\n  root.InboxoraNativeI18n = {\n    normalize(value) { const tag = String(value || '').replace(/_/g, '-').toLowerCase(); return tag.startsWith('zh') ? 'zhCN' : Object.hasOwn(catalog, tag.split('-')[0]) ? tag.split('-')[0] : 'en'; },\n    text(language, key, values = {}) { const messages = catalog[this.normalize(language)]; const template = messages[key] || catalog.en[key] || key; return template.replace(/\\{\\{(\\w+)\\}\\}/g, (_token, name) => String(values[name] ?? '')); },\n  };\n})(globalThis);\n`);
  const escapeXml = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('"', '\\"').replaceAll('\n', '\\n');
  for (const [language, directory] of Object.entries(languageDirectories)) {
    outputs.set(`packages/android/app/src/main/res/${directory}/native_strings.xml`,
      '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from Inboxora locale catalogs. Do not edit. -->\n<resources>\n'
      + Object.entries(catalog[language]).map(([key,value]) => `    <string name="${androidName(key)}" formatted="false">${escapeXml(value)}</string>`).join('\n')
      + '\n</resources>\n');
  }
  // Installed Linux launchers read desktop actions directly, outside Electron.
  // Include every supported desktop-locale label and reuse the validated CLI routes.
  const packageFile = path.join(root, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(packageFile, 'utf8'));
  const desktopActions = {};
  for (const [key, route] of [['compose','new-mail'],['calendar','open-calendar'],['contacts','open-contacts']]) {
    const label = key[0].toUpperCase() + key.slice(1);
    const entry = { Name: catalog.en[key] };
    for (const language of Object.keys(languageDirectories)) entry[`Name[${language === 'zhCN' ? 'zh_CN' : language}]`] = catalog[language][key];
    entry.Exec = `/opt/Inboxora/Inboxora --inboxora-action=${route}`;
    entry.Icon = 'Inboxora';
    desktopActions[label] = entry;
  }
  pkg.build.linux.desktop.entry.Actions = Object.keys(desktopActions).join(';') + ';';
  pkg.build.linux.desktop.desktopActions = desktopActions;
  outputs.set('package.json', JSON.stringify(pkg, null, 2) + '\n');
  return outputs;
}
function generate(check = false) {
  for (const [relative, content] of buildOutputs()) {
    const file = path.join(root, relative);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) throw new Error(`Stale native translations: ${relative}; run npm run native:locales`);
    } else { fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, content); }
  }
}
module.exports = { buildOutputs, generate, aliases, languageDirectories };
if (require.main === module) generate(process.argv.includes('--check'));
